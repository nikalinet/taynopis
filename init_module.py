# «Тайнопись» — модуль инициализации (этап 2)
# Сценарий: режим -> текст -> сдвиг -> преобразование -> вывод результата

low = "абвгдеёжзийклмнопрстуфхцчшщъыьэюя"
up = low.upper()

print("=== Тайнопись: шифр Цезаря ===")
mode = int(input("Режим (1 — зашифровать, 2 — расшифровать): "))
text = input("Введите текст: ")
shift = int(input("Введите сдвиг (целое число): "))

k = shift * (3 - 2 * mode) % 33   # режим 1 -> +сдвиг, режим 2 -> -сдвиг
table = str.maketrans(low + up, low[k:] + low[:k] + up[k:] + up[:k])
result = text.translate(table)

print(f"Результат: {result}")
