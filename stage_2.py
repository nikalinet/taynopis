# «Тайнопись» - этап 2

low = "абвгдеёжзийклмнопрстуфхцчшщъыьэюя"
up = low.upper()

print("=== Тайнопись: шифр Цезаря ===")
mode = int(input("Чего изволишь, добрый молодец? (1 - утаить, 2 - явить): ")) #Выход будет добавлен, после темы с if-else
text = input("Молви слово тайное: ")
shift = int(input("На сколько шагов воротить? "))

k = shift * (3 - 2 * mode) % 33
table = str.maketrans(low + up, low[k:] + low[:k] + up[k:] + up[:k])
result = text.translate(table)

print(f"Лови письмецо заморское и шаг береги аки зеницу ока. Потеряешь - сам себя не прочтёшь: {result}")

print("Коли не сработало — то не моя вина, а Цезаря окаянного.")

